export function trackAdvice(track: LegalTrack): string {
  switch (track) {
    case "criminal":
      return "مسیر کیفری است: هدف مجازات و تعقیب متهم است، نه لزوماً وصول طلب. مطالبه ضرر و زیان ناشی از جرم را می‌توانید ضمن شکایت یا جداگانه در دادگاه حقوقی بخواهید.";
    case "civil":
      return "مسیر حقوقی است: هدف الزام طرف به انجام تعهد یا پرداخت است. تا وقتی رفتار وصف مجرمانه مستقل نداشته باشد، شکواییه کیفری رد یا منع تعقیب می‌شود.";
    case "both":
      return "هر دو مسیر ممکن است. کیفری برای مجازات (مثلاً چک یا کلاهبرداری) و حقوقی برای وصول وجه. اغلب بهتر است موازی و با مشاوره ثبت شوند؛ یکی جایگزین دیگری نیست.";
    case "admin":
      return "مسیر اداری است: طرف دعوا واحد دولتی است و مرجع دیوان عدالت اداری (ساجد)، نه دادگاه عمومی.";
  }
}
